import numpy as np
from simulator import solve_oxygen_profile, HYDROGELS, IMPLANTATION_SITES

def conduct_study():
    print("# РЕЗУЛЬТАТЫ СИСТЕМНОГО ИССЛЕДОВАНИЯ ПАРАМЕТРОВ ИНКАПСУЛЯЦИИ\n")
    
    D_alginate = HYDROGELS["alginate_2%"]["D"]
    
    # --- СЦЕНАРИЙ 1: Зависимость от толщины капсулы (L) ---
    # Фиксируем: плотность = 80 млн/мл, p_boundary = 30 mmHg (подкожная клетчатка)
    print("## Сценарий 1: Влияние толщины капсулы на выживаемость клеток в подкожной клетчатке")
    print("*(Плотность заселения: 80 млн/мл, pO₂ на границе: 30 mmHg, 2% Альгинат)*\n")
    print("| Полутолщина L (мкм) | Полная толщина (мкм) | Мин. pO₂ в центре (mmHg) | Выживаемость (%) | Секреция инсулина (%) | Статус |")
    print("|---------------------|----------------------|--------------------------|------------------|-----------------------|--------|")
    
    for L in [50, 100, 150, 200, 250, 300, 350, 400, 450, 500]:
        res = solve_oxygen_profile(L, 80, 30.0, D_alginate)
        vf = res["viable_fraction"]
        min_p = res["min_pO2"]
        ins = res["insulin_capacity"]
        
        if vf > 99.0:
            status = "🟢 Норма"
        elif vf > 90.0:
            status = "🟡 Легкая гипоксия"
        elif vf > 50.0:
            status = "🟠 Умеренный некроз"
        else:
            status = "🔴 Массовый некроз"
            
        print(f"| {L} | {L*2} | {min_p:.4f} | {vf:.1f}% | {ins:.1f}% | {status} |")
        
    print("\n" + "="*80 + "\n")
    
    # --- СЦЕНАРИЙ 2: Зависимость от плотности клеток (rho) ---
    # Фиксируем: полутолщина L = 200 мкм (полная 400 мкм), p_boundary = 30 mmHg (подкожная клетчатка)
    print("## Сценарий 2: Влияние плотности клеток на выживаемость и функциональность")
    print("*(Толщина капсулы: 400 мкм (L=200), pO₂ на границе: 30 mmHg, 2% Альгинат)*\n")
    print("| Плотность (млн/мл) | Мин. pO₂ в центре (mmHg) | Выживаемость (%) | Секреция инсулина (%) | Объемная доля клеток (%) | Статус |")
    print("|-------------------|--------------------------|------------------|-----------------------|--------------------------|--------|")
    
    for rho in [10, 30, 50, 80, 100, 120, 150, 180, 200, 250]:
        res = solve_oxygen_profile(200, rho, 30.0, D_alginate)
        vf = res["viable_fraction"]
        min_p = res["min_pO2"]
        ins = res["insulin_capacity"]
        cell_vol = (rho * 1e6 * 1e-9) * 100.0
        
        if vf > 99.0:
            status = "🟢 Норма"
        elif vf > 90.0:
            status = "🟡 Легкая гипоксия"
        elif vf > 50.0:
            status = "🟠 Умеренный некроз"
        else:
            status = "🔴 Массовый некроз"
            
        print(f"| {rho} | {min_p:.4f} | {vf:.1f}% | {ins:.1f}% | {cell_vol:.1f}% | {status} |")
        
    print("\n" + "="*80 + "\n")
    
    # --- СЦЕНАРИЙ 3: Безопасный предел плотности для разных мест имплантации ---
    # Находим максимальную плотность клеток (млн/мл), которая сохраняет выживаемость >= 95%
    print("## Сценарий 3: Максимальная безопасная плотность клеток (Выживаемость >= 95%) в зависимости от толщины и места имплантации")
    print("*(2% Альгинат)*\n")
    print("| Полутолщина L (мкм) | Артериальное (~95 mmHg) | Венозное (~40 mmHg) | Подкожное (~30 mmHg) | Зона фиброза (~10 mmHg) |")
    print("|---------------------|------------------------|--------------------|----------------------|------------------------|")
    
    for L in [100, 150, 200, 250, 300, 400]:
        row_str = f"| {L} |"
        for site_key, site_info in IMPLANTATION_SITES.items():
            pO2_b = site_info["pO2"]
            max_safe_rho = 0
            for rho in range(5, 400, 5):
                res = solve_oxygen_profile(L, rho, pO2_b, D_alginate)
                if res["viable_fraction"] >= 95.0:
                    max_safe_rho = rho
                else:
                    break
            
            if max_safe_rho == 0:
                row_str += " Недостижимо |"
            else:
                row_str += f" {max_safe_rho} млн/мл |"
        print(row_str)

if __name__ == "__main__":
    conduct_study()
